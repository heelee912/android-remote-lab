package com.codex.remotecompanion;

import android.os.Process;
import android.os.SystemClock;
import android.util.Base64;

import org.json.JSONArray;
import org.json.JSONObject;

import java.io.ByteArrayOutputStream;
import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.io.InputStream;
import java.net.InetAddress;
import java.net.InetSocketAddress;
import java.net.ServerSocket;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;

/**
 * A small command broker launched by an already-authorized ADB shell.
 *
 * The process keeps the Android shell UID after adbd is stopped. It accepts
 * only loopback connections and authenticates every request with a random
 * capability generated by Companion. It never grants or changes a UID.
 */
public final class PrivilegedShellBroker {
    private static final int SHELL_UID = 2000;
    private static final int MAX_ARGUMENTS = 1024;
    private static final int MAX_ARGUMENT_BYTES = 64 * 1024;
    private static final int MAX_INPUT_BYTES = 8 * 1024 * 1024;
    private static final int MAX_STREAM_BYTES = 3 * 1024 * 1024;
    private static final long MAX_TIMEOUT_MILLIS = 10 * 60_000L;

    public static void main(String[] args) throws Exception {
        Configuration configuration = Configuration.parse(args);
        if (Process.myUid() != SHELL_UID) {
            throw new SecurityException("Privileged shell broker requires Android shell UID");
        }
        try (ServerSocket server = new ServerSocket()) {
            server.setReuseAddress(false);
            server.bind(new InetSocketAddress(InetAddress.getLoopbackAddress(), configuration.port), 8);
            while (true) {
                try (Socket socket = server.accept()) {
                    socket.setSoTimeout(30_000);
                    handle(socket, configuration.token);
                } catch (Throwable ignored) {
                    // One malformed or abandoned local request must not retire the broker.
                }
            }
        }
    }

    private static void handle(Socket socket, String expectedToken) throws Exception {
        DataInputStream input = new DataInputStream(socket.getInputStream());
        DataOutputStream output = new DataOutputStream(socket.getOutputStream());
        JSONObject request = Protocol.read(input);
        if (!constantTimeEquals(expectedToken, request.optString("token"))) {
            throw new SecurityException("Invalid privileged shell capability");
        }
        String action = request.getString("action");
        JSONObject result;
        if ("status".equals(action)) {
            result = new JSONObject()
                    .put("ready", true)
                    .put("uid", Process.myUid())
                    .put("pid", Process.myPid())
                    .put("startedElapsedRealtime", STARTED_ELAPSED_REALTIME);
        } else if ("exec".equals(action)) {
            result = execute(request);
        } else {
            throw new IllegalArgumentException("Unsupported privileged shell action");
        }
        Protocol.write(output, new JSONObject().put("ok", true).put("result", result));
    }

    private static JSONObject execute(JSONObject request) throws Exception {
        JSONArray encodedArguments = request.getJSONArray("argv");
        if (encodedArguments.length() == 0 || encodedArguments.length() > MAX_ARGUMENTS) {
            throw new IllegalArgumentException("Invalid privileged shell argument count");
        }
        List<String> arguments = new ArrayList<>(encodedArguments.length());
        int argumentBytes = 0;
        for (int index = 0; index < encodedArguments.length(); index++) {
            String value = encodedArguments.getString(index);
            if (value.indexOf('\0') >= 0) throw new IllegalArgumentException("NUL in argument");
            argumentBytes += value.getBytes(StandardCharsets.UTF_8).length;
            if (argumentBytes > MAX_ARGUMENT_BYTES) throw new IllegalArgumentException("Arguments exceed limit");
            arguments.add(value);
        }
        long timeoutMillis = request.optLong("timeoutMillis", 60_000L);
        if (timeoutMillis < 100L || timeoutMillis > MAX_TIMEOUT_MILLIS) {
            throw new IllegalArgumentException("Invalid privileged shell timeout");
        }
        byte[] standardInput = request.has("stdinBase64")
                ? Base64.decode(request.getString("stdinBase64"), Base64.DEFAULT) : new byte[0];
        if (standardInput.length > MAX_INPUT_BYTES) throw new IllegalArgumentException("Input exceeds limit");

        java.lang.Process child = new ProcessBuilder(arguments).start();
        StreamCapture stdout = new StreamCapture(child.getInputStream(), child);
        StreamCapture stderr = new StreamCapture(child.getErrorStream(), child);
        Thread stdoutThread = new Thread(stdout, "privileged-shell-stdout");
        Thread stderrThread = new Thread(stderr, "privileged-shell-stderr");
        stdoutThread.start();
        stderrThread.start();
        try {
            child.getOutputStream().write(standardInput);
            child.getOutputStream().close();
            boolean completed = child.waitFor(timeoutMillis, TimeUnit.MILLISECONDS);
            if (!completed) {
                child.destroy();
                if (!child.waitFor(1_000L, TimeUnit.MILLISECONDS)) child.destroyForcibly();
            }
            stdoutThread.join(2_000L);
            stderrThread.join(2_000L);
            if (stdout.overflow || stderr.overflow) {
                return new JSONObject()
                        .put("exitCode", 1)
                        .put("error", "privileged-shell-output-limit-exceeded")
                        .put("outcome", "confirmed-failed");
            }
            if (!completed) {
                return new JSONObject()
                        .put("exitCode", JSONObject.NULL)
                        .put("error", "privileged-shell-timeout")
                        .put("outcome", "unconfirmed");
            }
            return new JSONObject()
                    .put("exitCode", child.exitValue())
                    .put("stdoutBase64", Base64.encodeToString(stdout.bytes(), Base64.NO_WRAP))
                    .put("stderrBase64", Base64.encodeToString(stderr.bytes(), Base64.NO_WRAP));
        } finally {
            child.destroy();
            java.util.Arrays.fill(standardInput, (byte) 0);
        }
    }

    private static boolean constantTimeEquals(String expected, String actual) {
        return MessageDigest.isEqual(
                expected.getBytes(StandardCharsets.UTF_8),
                actual.getBytes(StandardCharsets.UTF_8));
    }

    private static final long STARTED_ELAPSED_REALTIME = SystemClock.elapsedRealtime();

    private static final class StreamCapture implements Runnable {
        private final InputStream input;
        private final java.lang.Process child;
        private final ByteArrayOutputStream output = new ByteArrayOutputStream();
        private volatile boolean overflow;

        StreamCapture(InputStream input, java.lang.Process child) {
            this.input = input;
            this.child = child;
        }

        @Override
        public void run() {
            byte[] buffer = new byte[32 * 1024];
            try {
                int length;
                while ((length = input.read(buffer)) != -1) {
                    if (output.size() + length > MAX_STREAM_BYTES) {
                        overflow = true;
                        child.destroy();
                        return;
                    }
                    output.write(buffer, 0, length);
                }
            } catch (Exception ignored) {
            }
        }

        byte[] bytes() {
            return output.toByteArray();
        }
    }

    private static final class Configuration {
        final int port;
        final String token;

        Configuration(int port, String token) {
            this.port = port;
            this.token = token;
        }

        static Configuration parse(String[] args) {
            int port = 0;
            String token = null;
            for (int index = 0; index + 1 < args.length; index += 2) {
                if ("--port".equals(args[index])) port = Integer.parseInt(args[index + 1]);
                else if ("--token".equals(args[index])) token = args[index + 1];
                else throw new IllegalArgumentException("Unknown privileged shell option");
            }
            if (port < 1024 || port > 65535 || token == null || !token.matches("[a-f0-9]{64}")) {
                throw new IllegalArgumentException("Invalid privileged shell configuration");
            }
            return new Configuration(port, token);
        }
    }

    private PrivilegedShellBroker() {}
}
